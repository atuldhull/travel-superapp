#!/usr/bin/env node
/**
 * docs-api-build.cjs — emit the bundled (offline-capable) Redoc page.
 *
 * Wraps `@redocly/cli build-docs` so we have a stable `pnpm docs:api:build`
 * entry point. Writes `docs/api/index.bundled.html` (~1.8 MB single-file).
 *
 * The thin shell at `docs/api/index.html` is the *default* viewer — it
 * fetches the YAML at runtime and so never drifts. The bundled file is
 * useful when:
 *   - you need offline browsing
 *   - you're shipping the docs to a host that can't serve YAML
 *   - you want a single asset to attach to a release
 *
 * `docs/api/index.bundled.html` is gitignored (see .gitignore) — it's a
 * derived artifact regenerated by [.github/workflows/docs-api.yml] before
 * publishing to GitHub Pages.
 *
 * Installed by [P3] of the Documentation 8.5→10 series.
 */

const { spawnSync } = require('node:child_process');
const path = require('node:path');
const fs = require('node:fs');

const repoRoot = path.resolve(__dirname, '..');
const specPath = path.join(repoRoot, 'docs', 'api', 'openapi.yaml');
const outPath = path.join(repoRoot, 'docs', 'api', 'index.bundled.html');

if (!fs.existsSync(specPath)) {
  console.error(`✗ ${path.relative(repoRoot, specPath)} not found.`);
  console.error('  Run `pnpm --filter=api api:openapi` first to emit the spec.');
  process.exit(1);
}

console.log(`▸ bundling docs/api/openapi.yaml → ${path.relative(repoRoot, outPath)}`);

// `shell: true` is required on Windows so PATHEXT resolves `npx.cmd`.
// Args are joined and quoted by the shell — since none contain shell
// metacharacters under our control (specPath / outPath are repo-local),
// the quoting is safe.
const result = spawnSync(
  'npx',
  ['-y', '@redocly/cli@latest', 'build-docs', `"${specPath}"`, '-o', `"${outPath}"`],
  { stdio: 'inherit', cwd: repoRoot, shell: true },
);

if (result.status !== 0) {
  console.error(`✗ redocly build-docs exited ${result.status}`);
  process.exit(result.status ?? 1);
}

const sizeKb = Math.round(fs.statSync(outPath).size / 1024);
console.log(`✓ wrote ${path.relative(repoRoot, outPath)} (${sizeKb} KiB)`);
console.log('  open it directly in any browser — no server needed.');
